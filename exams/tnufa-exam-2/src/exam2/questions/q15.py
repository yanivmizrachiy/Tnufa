# -*- coding: utf-8 -*-
"""Q15 — geometry with algebra: rectangle sides from the perimeter, and a claim about scaling the area."""
from ..model import Question, Part
from .. import html as H
from .. import svg as S

PERIM = 26


def check():
    x = 5
    assert 2 * x + 2 * (x + 3) == PERIM
    assert x * (x + 3) == 40 and (2 * x) * (2 * (x + 3)) == 160 == 4 * 40


def figure():
    x0, y0, w, h = 60, 40, 300, 170
    b = S.rect(x0, y0, w, h, S.PALE, S.NAVY, 2)
    b += S.t(x0 + w / 2, y0 + h + 28, "x + 3", 17, ltr=True, w=600)
    b += S.t(x0 + w + 26, y0 + h / 2 + 6, "x", 17, ltr=True, w=600)
    return S.svg(420, 250, b, "מלבן שרוחבו x ואורכו x + 3", maxw=260)


