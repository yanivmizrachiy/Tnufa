        parts=[a, b],
        reference="הקרוב ביותר: שאלה 12 במבחן הרשמי (מלבן מארבעה מלבנים זהים, היקף כביטוי ושטח) ושאלה 15 במבחן התרגול הקודם (מלבן מחולק, פילוג). הבדלים: (1) המלבן אינו מחולק; (2) ההיקף נתון כמספר ומוצאים את x (כיוון הפוך); (3) הסעיף השני הוא טענה על הגדלה פי 2 — תפיסת יחס שטחים שלא נבדקה בייחוס; (4) אין רב־ברירה.",
