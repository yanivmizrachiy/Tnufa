        claim="התלמיד מתרגם תיאור מילולי של מלבן למשוואה, ומבחין בין שינוי אורכים לשינוי שטח.",
        evidence="5 ו־8 עם משוואה; &quot;לא&quot; עם 40 לעומת 160 (פי 4).",
        task="מידול אלגברי; ביקורת טענה בעזרת חישוב או טיעון כללי.",
