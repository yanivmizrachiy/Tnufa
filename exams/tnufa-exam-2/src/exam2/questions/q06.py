# -*- coding: utf-8 -*-
"""Q6 — algebra: equation with fractions (binomial numerators)."""
from fractions import Fraction as F
from ..model import Question, Part
from .. import html as H


def check():
    x = F(13)
    assert (x + 2) / 3 - (x - 1) / 4 == 2


def build():
    eq = H.m('%s − %s = 2' % (H.frac("x + 2", "3"), H.frac("x − 1", "4")))
    p = Part(
        "", 5, "algorithmic",
        "<p>פתרו את המשוואה שלפניכם: &nbsp; %s</p><p>הציגו את דרך הפתרון.</p>%s%s" % (
            eq, H.work(168), H.ans('תשובה: &nbsp;<bdi dir="ltr" class="math">x = %s</bdi>' % H.BLANK)),
        H.m("x = 13"),
        "כופלים במכנה המשותף 12: %s. פותחים סוגריים: %s. מכנסים: %s, ולכן %s. בדיקה: %s." % (
            H.m("4(x + 2) − 3(x − 1) = 24"), H.m("4x + 8 − 3x + 3 = 24"), H.m("x + 11 = 24"), H.m("x = 13"),
            H.m("15/3 − 12/4 = 5 − 3 = 2")),
        [(5, "%s עם דרך פתרון נכונה." % H.m("x = 13")),
         (3, "טעות אחת (סימן אחרי המינוס, הכפלה חלקית של אגף ימין, או פילוג חלקי) ותשובה עקבית."),
         (1, "כפל נכון במכנה משותף ללא המשך, שתי טעויות, או תשובה נכונה ללא דרך."),
         (0, "כל אפשרות אחרת.")],
        alternatives="חיבור שברים לפני ההכפלה: %s, ואז %s." % (
            H.m(H.frac("4(x + 2) − 3(x − 1)", "12") + " = 2"), H.m("x + 11 = 24")),
        errors="%s (אי־פילוג המינוס על −1) ← %s; שכחת הכפלת 2 ב־12 ← %s; פילוג חלקי %s." % (
            H.m("4x + 8 − 3x − 3 = 24"), H.m("x = 19"), H.m("x = −9"), H.m("4x + 2 − 3x − 1")),
    )
    return Question(
        n=6, domain="algebra", topic="משוואה עם שברים", skill="מכנה משותף; פילוג מינוס על דו־איבר; פתרון משוואה",
        claim="התלמיד מסלק מכנים נכון ומטפל במינוס לפני סוגריים.",
        evidence="כפל נכון ב־12, פתיחת סוגריים עם סימנים נכונים, תשובה 13.",
        task="בחירת מכנה משותף, פילוג, כינוס ובידוד הנעלם.",
        difficulty="mid", representations=["סימבולי"], literacy=False, minutes=4,
        stem="",
        parts=[p],
        reference="הקרוב ביותר: שאלה 11 במבחן הרשמי (5x/6 + (1−3x)/2 = x/3). הבדלים: (1) מונים דו־איבריים בשני השברים; (2) חיסור בין השברים (מבחן למינוס לפני סוגריים); (3) אגף ימין מספר ולא שבר עם נעלם; (4) מכנה משותף 12 במקום 6 ופתרון שלם.",
        accessibility="ללא טקסט; שברים מוצגים אנכית וברור; מקום פתרון גדול.",
        notes="מרבית הטעויות הן סימן המינוס לפני הסוגריים — לתרגל &quot;המינוס חל על כל המונה&quot;.",
        check=check,
    )
