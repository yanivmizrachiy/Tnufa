"""Q9 — algebra: a linear inequality, then marking which given numbers solve it."""
from ..model import Question, Part
from .. import html as H

CANDS = (-4, 0, 4, 5.5, 10)


def holds(x):
    return 2 * (x + 3) <= 5 * x - 6


def check():
    assert [holds(x) for x in CANDS] == [False, False, True, True, True]
    assert holds(4) and not holds(3.99)


