def check():
    # construct numerically: A(0,h), B(-b,0), C(b,0), D=(-b+d,0), E=(b-d,0) → AD = AE
    b, h, d = 6, 7, 2
    A, D, E = (0, h), (-b + d, 0), (b - d, 0)
    assert math.dist(A, D) == math.dist(A, E)


def figure():
    Bp, Cp = (60, 230), (420, 230)
    Ap = (240, 40)
    Dp = (Bp[0] + 85, 230)
    Ep = (Cp[0] - 85, 230)
    b = S.poly([Ap, Bp, Cp], S.PALE, S.NAVY, 2.2)
    b += S.line(Ap[0], Ap[1], Dp[0], Dp[1], S.G3, 2) + S.line(Ap[0], Ap[1], Ep[0], Ep[1], S.G3, 2)
    b += S.tick(Ap, Bp, 1, 7) + S.tick(Ap, Cp, 1, 7)
    b += S.tick(Bp, Dp, 2, 6) + S.tick(Ep, Cp, 2, 6)
    for p in (Ap, Bp, Cp, Dp, Ep):
        b += S.dot(p)
    b += S.label(Ap, "A", 0, -12) + S.label(Bp, "B", -16, 8) + S.label(Cp, "C", 16, 8) + S.label(Dp, "D", 0, 24) + S.label(Ep, "E", 0, 24)
    return S.svg(480, 270, b, "משולש שווה-שוקיים ABC, ועל הבסיס נקודות D ו-E כך ש-BD = CE", maxw=360)


