"""Q13 — geometry / literacy: Pythagoras on a TV screen (diagonal, inches, and the inverse problem)."""
import math
from ..model import Question, Part
from .. import html as H
from .. import svg as S

W, HGT = 80, 60
CM_PER_INCH = 2.5
DIAG2, H2 = 65, 25


def check():
    assert math.hypot(W, HGT) == 100
    assert 100 / CM_PER_INCH == 40
    assert math.sqrt(DIAG2 ** 2 - H2 ** 2) == 60


def figure():
    x0, y0, w, h = 60, 30, 320, 240
    b = S.rect(x0 - 10, y0 - 10, w + 20, h + 20, "#1d2733", rx=10)
    b += S.rect(x0, y0, w, h, "#eaf2f7", S.NAVY, 1.6)
    b += S.line(x0, y0 + h, x0 + w, y0, S.AMBER, 2.4)
    b += S.t(x0 + w / 2 + 36, y0 + h / 2 - 10, "?", 24, ltr=True, w=700, c=S.AMBER)
    b += S.t(x0 + w / 2, y0 + h + 42, "80 ס״מ", 15, w=600)
    b += S.line(x0, y0 + h + 24, x0 + w, y0 + h + 24, S.MUTE, 1) + S.line(x0, y0 + h + 19, x0, y0 + h + 29, S.MUTE, 1) + S.line(x0 + w, y0 + h + 19, x0 + w, y0 + h + 29, S.MUTE, 1)
    b += S.t(x0 + w + 44, y0 + h / 2 + 5, "60 ס״מ", 15, w=600)
    b += S.line(x0 + w + 24, y0, x0 + w + 24, y0 + h, S.MUTE, 1) + S.line(x0 + w + 19, y0, x0 + w + 29, y0, S.MUTE, 1) + S.line(x0 + w + 19, y0 + h, x0 + w + 29, y0 + h, S.MUTE, 1)
    b += S.right_mark((x0, y0 + h), (x0 + w, y0 + h), (x0, y0), 12)
    # stand
    b += S.rect(x0 + w / 2 - 30, y0 + h + 10, 60, 6, "#1d2733", rx=2)
    return S.svg(470, 320, b, "מסך טלוויזיה מלבני, רוחב 80 ס״מ וגובה 60 ס״מ, ואלכסון", maxw=330)


