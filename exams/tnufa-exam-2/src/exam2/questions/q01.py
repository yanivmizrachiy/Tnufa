# -*- coding: utf-8 -*-
"""Q1 — numbers: the value of a power and a square root, and a claim about powers to judge (easy opener)."""
import math
from ..model import Question, Part
from .. import html as H


def check():
    assert 3 ** 2 + math.isqrt(16) == 13
    assert 2 ** 5 == 32 and 5 ** 2 == 25 and 2 ** 5 != 5 ** 2
    assert 2 ** 4 == 4 ** 2 == 16     # used in the teacher's note: here the claim does hold


KEY = {   # answer key (מחוון תשובות): part → (answer, how)
    "א": ("ב: 13", "%s, %s, ולכן %s." % (H.m(H.sup("3", "2") + " = 3 · 3 = 9"), H.m(H.root("16") + " = 4"), H.m("9 + 4 = 13"))),
    "ב": ("לא", "%s, ואילו %s. החזקות שונות." % (H.m(H.sup("2", "5") + " = 2 · 2 · 2 · 2 · 2 = 32"), H.m(H.sup("5", "2") + " = 5 · 5 = 25"))),
}


def build():
    a = Part(
        "א", 2, "knowledge",
        "מהו הערך של הביטוי %s?" % H.m(H.sup("3", "2") + " + " + H.root("16")) +
        H.opts([H.m("10"), H.m("13"), H.m("17"), H.m("25")], 4),
        "ב. 13",
        "%s ו־%s, ולכן %s." % (H.m(H.sup("3", "2") + " = 3 · 3 = 9"), H.m(H.root("16") + " = 4"), H.m(H.sup("3", "2") + " + " + H.root("16") + " = 9 + 4 = 13")),
        [(2, "סימון ב בלבד."), (0, "כל אפשרות אחרת, כולל סימון יותר מתשובה אחת.")],
        errors="א (10) — חישוב %s; ג (17) — חישוב %s; ד (25) — שכחת השורש (%s)." % (
            H.m(H.sup("3", "2") + " = 3 · 2 = 6"), H.m(H.root("16") + " = 16 : 2 = 8"), H.m("9 + 16")),
    )
    b = Part(
        "ב", 2, "open",
        "דנה טוענת: &nbsp;%s<br>האם דנה צודקת?" % H.m(H.sup("2", "5") + " = " + H.sup("5", "2")) +
        H.yesno() + "<p>נמקו את תשובתכם בעזרת חישוב.</p>" + H.work(76),
        "לא",
        "%s ואילו %s. שני הצדדים אינם שווים, ולכן דנה אינה צודקת: החלפת הבסיס והמעריך משנה בדרך כלל את התוצאה." % (
            H.m(H.sup("2", "5") + " = 2 · 2 · 2 · 2 · 2 = 32"), H.m(H.sup("5", "2") + " = 5 · 5 = 25")),
        [(2, "סימון &quot;לא&quot; ונימוק המראה את שני הערכים (32 ו־25)."),
         (1, "סימון &quot;לא&quot; עם חישוב של צד אחד בלבד, או חישוב נכון של שני הצדדים ללא מסקנה."),
         (0, "כל אפשרות אחרת, כולל &quot;כן&quot; עם נימוק.")],
        alternatives="מספיק להראות ששני הצדדים שונים, למשל ש־%s גדול מ־%s." % (H.m(H.sup("2", "5")), H.m(H.sup("5", "2"))),
        errors="&quot;כן&quot; מאבחן קריאה של חזקה ככפל (%s ו־%s, ושניהם 10)." % (
            H.m(H.sup("2", "5") + " = 2 · 5"), H.m(H.sup("5", "2") + " = 5 · 2")),
        reasoning_credit=True,
    )
    return Question(
        n=1, domain="numbers", topic="חזקות ושורשים ריבועיים", skill="משמעות החזקה והשורש הריבועי; בדיקת טענה בעזרת חישוב",
        claim="התלמיד יודע לחשב חזקה ושורש ריבועי של מספרים קטנים, ויודע שבחזקה אי־אפשר להחליף בין הבסיס למעריך.",
        evidence="בחירת ב בסעיף א; בסעיף ב חישוב שני הצדדים (32 לעומת 25) ומסקנה.",
        task="שאלת פתיחה קלה: חישוב ערך ביטוי; הכרעה בטענה מספרית ונימוקה בחישוב.",
        difficulty="low", representations=["סימבולי → מספרי"], literacy=False, minutes=2,
        stem="",
        parts=[a, b],
        reference="הקרוב ביותר: שאלה 11 במבחן התרגול הקודם (√30 על ישר המספרים). הבדלים: (1) אין ישר מספרים וקנה־מידה; (2) הסעיף הראשון בודק חישוב חזקה ושורש ולא אומדן; (3) הסעיף השני הוא ביקורת טענה ולא זיהוי; (4) נדרש חישוב מנומק ולא רב־ברירה בלבד.",
        accessibility="טקסט קצר ומספרים קטנים; אפשר לחשב בעל־פה; אין תלות בסרטוט.",
        notes="אם תלמידים רבים סימנו &quot;כן&quot; — לחזור על משמעות החזקה ככפל חוזר. דוגמה מעניינת להמשך: %s, ובכל זאת %s." % (
            H.m(H.sup("2", "4") + " = " + H.sup("4", "2") + " = 16"), H.m(H.sup("2", "5") + " ≠ " + H.sup("5", "2"))),
        check=check, critique=True,
    )
