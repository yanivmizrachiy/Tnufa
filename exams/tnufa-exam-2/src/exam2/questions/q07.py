# -*- coding: utf-8 -*-
"""Q7 — algebra / literacy: a print shop's price as a linear function (table → formula → inverse → comparison)."""
from ..model import Question, Part
from .. import html as H

SETUP, PER = 80, 6         # shop A: setup fee + per booklet
AVG_X = 40                 # part d: order size for the average price per booklet
PAID = 440
TABLE_X = (10, 20, 50)


def price(x):
    return SETUP + PER * x


def check():
    assert [price(x) for x in TABLE_X] == [140, 200, 380]
    assert (PAID - SETUP) / PER == 60
    assert price(AVG_X) / AVG_X == 8
    avg = [price(x) / x for x in (10, 20, 40, 80, 400)]
    assert avg == sorted(avg, reverse=True) and all(v > PER for v in avg)       # strictly decreasing, always above 6


KEY = {   # answer key (מחוון תשובות): part → (answer, how)
    "א": ("140, 200, 380", "%s, וכך גם ל־20 ול־50 חוברות." % H.m("80 + 6 · 10 = 140")),
    "ב": (H.m("y = 6x + 80"), "תשלום קבוע של 80 שקלים, ועוד 6 שקלים לכל חוברת."),
    "ג": ("60 חוברות", "%s, ולכן %s." % (H.m("6x + 80 = 440"), H.m("6x = 360"))),
    "ד": ("8 שקלים לחוברת<br>כן, דנה צודקת", "%s. המחיר הממוצע הוא %s, והוא קטן ככל שמספר החוברות גדל, כי תשלום ההכנה מתחלק על יותר חוברות." % (
        H.m("(80 + 6 · 40) : 40 = 320 : 40 = 8"), H.m("6 + 80 : x"))),
}


