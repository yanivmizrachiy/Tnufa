# -*- coding: utf-8 -*-
"""Q3 — numbers: finding the original price from a price after discount (reverse percent)."""
from ..model import Question, Part
from .. import html as H
from .. import svg as S

DISCOUNT = 25
AFTER = 90


def check():
    assert AFTER / (1 - DISCOUNT / 100) == 120
    assert AFTER * (1 + DISCOUNT / 100) == 112.5      # the distractor


def figure():
    b = ""
    # right: the unknown original price; middle: the discount; left: the price now. Arrows read right-to-left.
    pts = [(300, 20), (420, 20), (450, 60), (420, 100), (300, 100)]
    b += S.poly(pts, "#fff", S.MUTE, 1.6, 'stroke-dasharray="5 4"') + S.circ(425, 60, 5, "#fff", S.MUTE, 1.4)
    b += S.t(352, 52, "המחיר לפני", 13, c=S.MUTE) + S.t(352, 84, "?", 24, w=700, c=S.AMBER, ltr=True)
    b += S.circ(225, 60, 38, S.AMBER) + S.t(225, 55, "הוזלה", 13, w=600, c="#fff") + S.t(225, 76, "25%", 17, w=700, c="#fff", ltr=True)
    pts2 = [(20, 20), (140, 20), (170, 60), (140, 100), (20, 100)]
    b += S.poly(pts2, S.PALE, S.G3, 1.8) + S.circ(145, 60, 5, "#fff", S.G3, 1.4)
    b += S.t(72, 52, "המחיר עכשיו", 13, c=S.MUTE) + S.t(72, 82, "90 ₪", 22, w=700, c=S.G3)
    b += S.arrow(296, 60, 268, 60, S.MUTE, 1.8) + S.arrow(182, 60, 174, 60, S.MUTE, 1.8)
    return S.svg(470, 120, b, "המחיר לפני ההוזלה אינו ידוע; אחרי הוזלה של 25% המחיר 90 שקלים", maxw=380)


def build():
    p = Part(
        "", 5, "process",
        "<p>מה היה מחיר החולצה לפני ההוזלה?</p>" +
        H.opts(["112.5 שקלים", "115 שקלים", "120 שקלים", "135 שקלים"], 2) +
        "<p>הציגו את דרך הפתרון.</p>" + H.work(112),
        "ג. 120 שקלים",
        "אחרי הוזלה של 25%% נשארים 75%% מהמחיר המקורי. אם המחיר המקורי הוא %s, אז %s, ולכן %s." % (
            H.m("x"), H.m("0.75x = 90"), H.m("x = 90 : 0.75 = 120")),
        [(5, "סימון ג עם דרך פתרון תקפה: משוואה, חלוקה ב־0.75, חישוב לפי 25% = רבע (90 הם 3 רבעים, רבע = 30, המחיר 120), או בדיקת האפשרות שנבחרה: 120 · 0.75 = 90."),
         (3, "דרך פתרון נכונה עם טעות חישוב אחת, וסימון עקבי עם הטעות."),
         (1, "סימון ג ללא דרך פתרון."),
         (0, "כל אפשרות אחרת.")],
        alternatives="חשיבה בחלקים: 25%% = רבע, ולכן 90 שקלים הם 3 רבעים → רבע = 30 → המחיר 120. או בדיקה שיטתית של האפשרויות: %s." % H.m("120 · 0.75 = 90"),
        errors="א (112.5 = 90·1.25) מאבחן את הטעות הנפוצה: חישוב 25% מהמחיר אחרי ההוזלה במקום מהמחיר המקורי. ב (115 = 90 + 25) מאבחן הוספת האחוז כשקלים; ד (135 = 90 + 45) מאבחן חישוב 50% או חיבור שרירותי.",
        reasoning_credit=True,
    )
    return Question(
        n=3, domain="numbers", topic="אחוזים — מציאת השלם", skill="מציאת ערך מקורי לפי ערך אחרי שינוי באחוזים",
        claim="התלמיד מבין שהאחוז מחושב מהמחיר המקורי, ויודע להפוך את הפעולה (או להציב ולבדוק).",
        evidence="בחירת 120 עם דרך שמראה 90 = 75% מהמקור.",
        task="בניית משוואה או חשיבה בחלקים ממצב מילולי; בחירת תשובה והצגת דרך.",
        difficulty="mid", representations=["מילולי → סימבולי/מספרי", "ציור → מספרי"], literacy=True, minutes=4,
        stem="<p>בחנות בגדים הוזל מחירה של חולצה ב־%d%%. המחיר אחרי ההוזלה הוא %d שקלים.</p>%s" % (DISCOUNT, AFTER, figure()),
        parts=[p],
        reference="הקרוב ביותר: שאלה 3 במבחן התרגול הקודם (התייקרות ואז הוזלה ב־20%). הבדלים: (1) כאן נדרש למצוא את השלם מתוך החלק (חישוב הפוך), ולא את התוצאה; (2) שינוי אחד ולא שניים; (3) רב־ברירה עם מסיחים מאבחנים + דרך; (4) אין טענה לביקורת אלא בחירת דרך.",
        accessibility="משפט אחד; הציור מסכם את הנתונים; מספרים נוחים לחישוב עם מחשבון.",
        notes="תלמידים שבחרו א — להדגיש &quot;ממה מחשבים את האחוז&quot;; לתרגל בעיות הפוכות עם ציור של 4 רבעים.",
        check=check, strategy=True,
    )
