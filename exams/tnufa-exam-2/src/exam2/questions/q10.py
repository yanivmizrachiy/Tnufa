LA = (-2, 4)     # y = -2x + 4
LB = (1, -3)     # y = x - 3
LC = (-1, 2)     # y = -x + 2  (decoy: same x-intercept as a, same y-intercept as d)
D_THROUGH = (0, 2)


def check():
    m, k = LA
    assert m * 0 + k == 4 and m * 2 + k == 0
    m, k = LB
    assert m * 0 + k == -3 and m * 3 + k == 0
    m, k = LC
    assert m * 0 + k == 2 and m * 2 + k == 0 and LA[0] * 2 + LA[1] == 0      # a and c meet at (2, 0)
    assert LB[0] * D_THROUGH[0] + 2 == D_THROUGH[1] and LC != LB
    # part d: a and c meet at (2, 0); b does not pass there (b(2) = -1), so the three lines do not share a point
    assert LA[0] * 2 + LA[1] == LC[0] * 2 + LC[1] == 0 and LB[0] * 2 + LB[1] == -1


def figure():
    p = S.Plane(-2, 6, -4, 6, u=30)
    b = p.b
    b += p.line_through(LA[0], LA[1], S.BLUE, 2.6) + p.line_through(LB[0], LB[1], S.G3, 2.6) + p.line_through(LC[0], LC[1], S.AMBER, 2.6)
    # labels near the ends of each line
    b += S.t(p.sx(-1.3) + 14, p.sy(LA[0] * -1.3 + LA[1]) + 4, "a", 17, ltr=True, w=700, c=S.BLUE)
    b += S.t(p.sx(5.6) - 2, p.sy(LB[0] * 5.6 + LB[1]) - 12, "b", 17, ltr=True, w=700, c=S.G3)
    b += S.t(p.sx(5.4) + 14, p.sy(LC[0] * 5.4 + LC[1]) + 6, "c", 17, ltr=True, w=700, c=S.AMBER)
    return S.svg(int(p.W), int(p.H), b, "מערכת צירים ובה שלושה ישרים a, b ו-c", maxw=330)


