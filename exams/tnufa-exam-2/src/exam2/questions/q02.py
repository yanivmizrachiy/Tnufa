    a = Part(
        "א", 3, "algorithmic",
        "כמה מיליליטר תרכיז דרושים להכנת %d מיליליטר מיץ לפי ההוראות? הציגו את דרך הפתרון." % JUICE_ML +
        H.work(76) + H.ans("תשובה: %s מיליליטר" % H.BLANK),
        "120 מיליליטר",
        "לפי היחס, המיץ מורכב מ־5 חלקים שווים: חלק אחד תרכיז ו־4 חלקים מים. %s, ולכן דרושים 120 מיליליטר תרכיז (ו־480 מיליליטר מים)." % H.m("600 : 5 = 120"),
        [(3, "תשובה 120 עם דרך פתרון נכונה (חלוקה ל־5 חלקים או דרך שקולה)."),
         (2, "דרך נכונה עם טעות חישוב אחת, ותשובה עקבית עם הטעות."),
         (1, "זיהוי שהמיץ מורכב מ־5 חלקים (למשל 600 : 5) ללא השלמה, או תשובה 120 ללא דרך."),
         (0, "כל אפשרות אחרת.")],
        alternatives="טבלת יחס: 100 תרכיז ↔ 400 מים ↔ 500 מיץ; 120 ↔ 480 ↔ 600. או: התרכיז הוא %s מהמיץ, %s." % (H.frac("1", "5"), H.m("600 · " + "<span class=\"frac\"><span class=\"fn\">1</span><span class=\"fd\">5</span></span>" + " = 120")),
        errors="150 (חלוקה ב־4) מאבחן התייחסות ליחס 1:4 כיחס חלק־לשלם במקום חלק־לחלק.",
    )
    b = Part(
        "ב", 3, "open",
        "אייל ערבב %d מיליליטר תרכיז עם %d מיליליטר מים. בהשוואה למיץ שלפי ההוראות, המיץ של אייל הוא:" % EYAL +
        H.opts(["מרוכז יותר (טעם חזק יותר)", "מרוכז פחות (טעם חלש יותר)", "מרוכז בדיוק באותה מידה"], 1) +
        "<p>נמקו את תשובתכם בעזרת חישוב.</p>" + H.work(94),
        "ב. מרוכז פחות",
        "לפי ההוראות, על 200 מיליליטר תרכיז דרושים %s מיליליטר מים. אייל שם 900 מיליליטר מים — יותר מים לאותה כמות תרכיז, ולכן המיץ שלו מרוכז פחות." % H.m("200 · 4 = 800"),
        [(3, "סימון ב עם נימוק כמותי תקף (השוואת כמות המים הנדרשת, השוואת יחסים, או השוואת חלק התרכיז בתערובת)."),
         (2, "סימון ב עם חישוב נכון אך נימוק חסר, או נימוק מלא עם טעות חישוב קטנה."),
         (1, "סימון ב ללא נימוק, או השוואה נכונה של היחסים ללא מסקנה."),
         (0, "כל אפשרות אחרת.")],
        alternatives="השוואת יחסים: %s לעומת %s; או חלק התרכיז: %s לעומת %s." % (
            H.m("900 : 200 = 4.5"), H.m("4 : 1 = 4"), H.m("200 / 1100 ≈ 0.18"), H.m("1 / 5 = 0.2")),
        errors="סימון א עם נימוק &quot;200 זה יותר מ־1&quot; מאבחן השוואת כמויות מוחלטות במקום יחסים. סימון ג מאבחן אי־זיהוי שינוי ביחס.",
        reasoning_credit=True,
    )
    return Question(
        n=2, domain="numbers", topic="יחס", skill="חלוקה לפי יחס; השוואת יחסים בהקשר",
        claim="התלמיד מפרש יחס חלק־לחלק, מחלק כמות לפי יחס, ומשווה תערובות לפי יחס ולא לפי כמות מוחלטת.",
        evidence="120 עם דרך; הכרעה &quot;מרוכז פחות&quot; עם השוואה כמותית.",
        task="תרגום הוראה מילולית ליחס; חישוב חלק מכמות; הכרעה מנומקת בהשוואת יחסים.",
        difficulty="mid", representations=["מילולי → יחס → מספרי", "ציור → יחס"], literacy=True, minutes=5,
        stem="<p>להכנת מיץ לפי ההוראות שעל בקבוק התרכיז מערבבים תרכיז ומים ביחס %s (על כל כוס תרכיז — 4&nbsp;כוסות מים).</p>%s" % (
            H.m("1 : 4"), figure()),
        parts=[a, b],
        reference="הקרוב ביותר: שאלה 10 במבחן הרשמי (אחוז התקציב למזון) ושאלה 13 במבחן התרגול הקודם (אחוזים מסקר). הבדלים: (1) יחס חלק־לחלק ולא אחוז; (2) מצב מציאותי של תערובת ולא תקציב/סקר; (3) נדרש להשוות שתי תערובות ולא לחשב ערך אחד; (4) פתוח להרבה דרכים (יחס, שבר, הכפלה) במקום רב־ברירה.",
        accessibility="ציור הכוסות מבהיר את משמעות היחס; מספרים נוחים; מחשבון זמין.",
        notes="סעיף ב הוא פריט חשיבה פרופורציונלית מובהק. תלמידים שבחרו א בגלל &quot;200 גדול מ־1&quot; זקוקים לעבודה על יחס כהשוואה כפלית.",
        check=check, strategy=True,
    )
