# -*- coding: utf-8 -*-
"""Q2 — numbers / literacy: ratio of concentrate to water."""
from ..model import Question, Part
from .. import html as H
from .. import svg as S

RATIO = (1, 4)          # concentrate : water
JUICE_ML = 600
EYAL = (200, 900)       # ml concentrate, ml water


def check():
    assert JUICE_ML / sum(RATIO) * RATIO[0] == 120
    assert EYAL[1] / EYAL[0] == 4.5 > RATIO[1] / RATIO[0]           # more water per unit of concentrate
    assert EYAL[0] / sum(EYAL) < RATIO[0] / sum(RATIO)               # smaller fraction of concentrate


def figure():
    b = ""
    x0, y = 60, 20

    def cup(x, fill, lab):
        out = S.path("M%d %d L%d %d L%d %d L%d %d Z" % (x - 22, y, x + 22, y, x + 16, y + 56, x - 16, y + 56), fill, S.G3, 1.6)
        out += S.t(x, y + 80, lab, 13, w=600, c=S.MUTE)
        return out
    b += cup(x0 + 4 * 92, "#2f7a5b", "תרכיז")
    for i in range(4):
        b += cup(x0 + i * 92 + 12, "#d9efff", "מים")
    b += S.t(x0 + 3 * 92 + 60, y + 36, "+", 26, ltr=True, w=600, c=S.MUTE)
    return S.svg(540, 110, b, "כוס תרכיז אחת וארבע כוסות מים", maxw=420)


KEY = {   # answer key (מחוון תשובות): part → (answer, how)
    "א": ("120 מיליליטר", "המיץ מורכב מ־5 חלקים שווים (1 + 4), ומהם חלק אחד תרכיז: %s." % H.m("600 : 5 = 120")),
    "ב": ("ב: מרוכז פחות", "לפי ההוראות ל־200 מ״ל תרכיז דרושים %s מ״ל מים, ואייל הוסיף 900 (יחס %s)." % (H.m("200 · 4 = 800"), H.m("1 : 4.5"))),
}


