# -*- coding: utf-8 -*-
"""Q17 — data / percent: a pie chart of club members; new members change the percentages."""
import math
from fractions import Fraction as F
from ..model import Question, Part
from .. import html as H
from .. import svg as S

TOTAL = 240
SHARE = [("כדורגל", 40), ("כדורסל", 25), ("שחייה", 20), ("אחר", 15)]
NEW_SOCCER = 24
TARGET_SWIM = 25


def check():
    assert sum(p for _, p in SHARE) == 100
    assert TOTAL * 20 // 100 == 48 and TOTAL * 40 // 100 == 96
    assert round(100 * (96 + NEW_SOCCER) / (TOTAL + NEW_SOCCER)) == 45
    x = F(TARGET_SWIM * TOTAL - 100 * 48, 100 - TARGET_SWIM)
    assert x == 16 and F(48 + 16, TOTAL + 16) == F(1, 4)


def figure():
    cx, cy, r = 150, 158, 105
    cols = [S.G3, S.BLUE, S.TURQ, "#b9c6d2"]
    b = ""
    a0 = -90
    for (name, pct), c in zip(SHARE, cols):
        a1 = a0 + 360 * pct / 100
        x0, y0 = cx + r * math.cos(math.radians(a0)), cy + r * math.sin(math.radians(a0))
        x1, y1 = cx + r * math.cos(math.radians(a1)), cy + r * math.sin(math.radians(a1))
        large = 1 if pct > 50 else 0
        b += '<path d="M%.2f %.2f L%.2f %.2f A%d %d 0 %d 1 %.2f %.2f Z" fill="%s" stroke="#fff" stroke-width="2"/>' % (
            cx, cy, x0, y0, r, r, large, x1, y1, c)
        mid = math.radians((a0 + a1) / 2)
        lx, ly = cx + r * 0.62 * math.cos(mid), cy + r * 0.62 * math.sin(mid)
        ink = "#fff" if c != "#b9c6d2" else S.INK
        b += S.t(lx, ly + 5, "%d%%" % pct, 15, ltr=True, w=700, c=ink)
        a0 = a1
    # legend
    ly = 100
    for (name, pct), c in zip(SHARE, cols):
        b += S.rect(392, ly - 11, 14, 14, c, rx=3) + S.t(384, ly, name, 14, "start", w=600)
        ly += 30
    b += S.t(cx, 30, "התפלגות חברי המועדון לפי ענף", 15, "middle", w=700, c=S.NAVY)
    return S.svg(520, 278, b, "דיאגרמת עיגול: כדורגל 40%, כדורסל 25%, שחייה 20%, אחר 15%", maxw=420)


KEY = {   # answer key (מחוון תשובות): part → (answer, how)
    "א": ("48 חברים", H.m("0.2 · 240 = 48")),
    "ב": ("בערך 45%", "בכדורגל %s חברים, ובסך הכול %s: %s." % (H.m("0.4 · 240 + 24 = 120"), H.m("264"), H.m("120 : 264 ≈ 0.45"))),
    "ג": ("16 חברים", "%s, ולכן %s, %s." % (H.m(H.frac("48 + x", "240 + x") + " = " + H.frac("1", "4")), H.m("192 + 4x = 240 + x"), H.m("x = 16"))),
}


def build():
    a = Part("א", 2, "algorithmic", "כמה חברים במועדון עוסקים בשחייה?" + H.ans("תשובה: %s חברים" % H.BLANK),
             "48", "%s." % H.m("240 · 0.2 = 48"), [(2, "48."), (1, "דרך נכונה עם טעות חישוב (למשל 240 : 5 שגוי)."), (0, "כל אפשרות אחרת.")],
             errors="20 — קריאת האחוז כמספר.")
    b = Part("ב", 2, "process",
             "בשנה הבאה יצטרפו למועדון %d חברים חדשים, כולם לענף הכדורגל, ומספר החברים בשאר הענפים לא ישתנה.<br>כמה אחוזים מכלל חברי המועדון יעסקו אז בכדורגל? עגלו לאחוז שלם. הציגו את דרך הפתרון." % NEW_SOCCER +
             H.work(76) + H.ans("תשובה: בערך %s%%" % H.BL_S),
             "בערך 45%", "כדורגל: %s חברים; סך החברים: %s. %s." % (H.m("96 + 24 = 120"), H.m("240 + 24 = 264"), H.m("120 : 264 ≈ 0.4545 → 45%")),
             [(2, "45% (או 45.5%) עם חישוב של חלק מתוך השלם החדש (264)."), (1, "חישוב 120 נכון עם חלוקה ב־240 (50%), או דרך נכונה עם טעות חישוב."),
              (0, "כל אפשרות אחרת, כולל 64% (40 + 24).")],
             errors="50% — התעלמות מהגידול בשלם; 64% — חיבור אחוז ומספר; 10% — 24 מתוך 240.", reasoning_credit=True)
    c = Part("ג", 3, "open",
             "נניח שהחברים החדשים מסעיף ב׳ <b>לא</b> הצטרפו. המועדון רוצה לצרף חברים חדשים לענף השחייה בלבד, כך שמספר העוסקים בשחייה יהיה <b>בדיוק</b> רבע (25%) מכלל החברים.<br>כמה חברים חדשים צריכים להצטרף לשחייה? הציגו את דרך הפתרון." +
             H.work(118) + H.ans("תשובה: %s חברים" % H.BLANK),
             "16", "נסמן ב־%s את מספר המצטרפים: %s → %s → %s → %s. בדיקה: %s." % (
                 H.m("x"), H.m(H.frac("48 + x", "240 + x") + " = " + H.frac("1", "4")), H.m("4(48 + x) = 240 + x"), H.m("192 + 4x = 240 + x"), H.m("x = 16"),
                 H.m("64 : 256 = 0.25")),
             [(3, "16 עם דרך תקפה (משוואה; או טיעון: שאר הענפים, 192, צריכים להיות 75% → סך 256 → 16; או ניסוי שיטתי שמסתיים ב־16 ובדיקה)."),
              (2, "משוואה נכונה עם טעות פתרון, או ניסוי שמגיע ל־16 ללא בדיקה/הסבר."),
              (1, "זיהוי שהשלם משתנה (למשל ניסיון ראשון שגוי 12 = 60 − 48 ואז המשך לא שלם), או 16 ללא דרך."),
              (0, "כל אפשרות אחרת, כולל 12 (25% מ־240 פחות 48).")],
             alternatives="192 חברים שאינם שחיינים הם 75% מהסך החדש → הסך 256 → 256 − 240 = 16. ניסוי וטעייה מסודר: 12 → 60/252 ≈ 23.8%; 16 → 64/256 = 25%.",
             errors="12 — חישוב 25% מהשלם הישן; 48 — הכפלת השחיינים &quot;כדי להגיע ל־25%&quot;.", reasoning_credit=True)
    return Question(
        n=17, domain="data", topic="דיאגרמת עיגול ואחוזים משתנים", skill="קריאת דיאגרמת עיגול; חלק מתוך שלם משתנה; בניית משוואה מתנאי אחוז",
        claim="התלמיד קורא דיאגרמת עיגול, מבין שהשלם משתנה כשמצטרפים חברים, ובונה משוואה (או טיעון שקול) מתנאי אחוז.",
        evidence="48; 45% עם 264 במכנה; 16 עם משוואה או טיעון 75%.",
        task="חישוב ישיר; חישוב עם שלם משתנה; חיפוש פתוח של כמות שמקיימת תנאי.",
        difficulty="high", representations=["דיאגרמת עיגול → מספרי", "מילולי → משוואה"], literacy=False, minutes=6,
        stem="<p>במועדון ספורט %d חברים, וכל חבר עוסק בענף אחד. הדיאגרמה שלפניכם מציגה את התפלגות החברים לפי ענף.</p>%s" % (TOTAL, figure()),
        parts=[a, b, c],
        reference="הקרוב ביותר: שאלה 5 במבחן הרשמי (דיאגרמת עמודות בחירות, 40% לסיבוב שני) ושאלה 13 במבחן התרגול הקודם (דיאגרמת עמודות סקר בשני בתי ספר). הבדלים: (1) דיאגרמת עיגול באחוזים, לא עמודות; (2) השלם משתנה בין הסעיפים — מושג שלא נבדק בייחוס; (3) סעיף ג דורש בניית משוואה מתנאי אחוז (חיפוש פתוח); (4) אין השוואה בין שתי קבוצות.",
        accessibility="דיאגרמה עם אחוזים כתובים בתוך הגזרות ומקרא; הצבעים נבדלים גם בבהירות (שחור־לבן); מחשבון זמין.",
        notes="סעיף ג הוא הפריט המאתגר ביותר במבחן; שימו לב לתלמידים שענו 12 — הם לא עדכנו את השלם.",
        check=check, strategy=True,
    )
