# -*- coding: utf-8 -*-
"""Q16 — data: mode, median and mean from a frequency table, and a claim about "most students"."""
import statistics
from ..model import Question, Part
from .. import html as H

FREQ = {0: 2, 1: 5, 2: 8, 3: 6, 4: 3, 5: 1}      # books read : number of students


def values():
    return sorted(k for k, v in FREQ.items() for _ in range(v))


def check():
    v = values()
    assert len(v) == 25 and statistics.mode(v) == 2 and statistics.median(v) == 2
    assert sum(v) == 56 and sum(v) / 25 == 2.24
    assert sum(c for k, c in FREQ.items() if k > 2) == 10 < 12.5


KEY = {   # answer key (מחוון תשובות): part → (answer, how)
    "א": ("25 תלמידים", H.m("2 + 5 + 8 + 6 + 3 + 1 = 25")),
    "ב": ("2 ספרים", "לערך 2 השכיחות הגבוהה ביותר (8 תלמידים)."),
    "ג": ("2 ספרים", "החציון הוא הערך ה־13 בסדר עולה: עד ספר אחד — 7 תלמידים, עד 2 ספרים — 15 תלמידים."),
    "ד": ("2.24 ספרים", "סכום הספרים %s, ו־%s." % (H.m("0·2 + 1·5 + 2·8 + 3·6 + 4·3 + 5·1 = 56"), H.m("56 : 25 = 2.24"))),
    "ה": ("לא", "רק %s תלמידים מתוך 25 קראו יותר מ־2 ספרים. ממוצע גדול מ־2 אינו אומר שרוב התלמידים מעליו." % H.m("6 + 3 + 1 = 10")),
}


def build():
    tbl = H.kv_table([["מספר הספרים"] + [str(k) for k in FREQ], ["מספר התלמידים"] + [str(v) for v in FREQ.values()]])
    a = Part("א", 1, "knowledge", "כמה תלמידים נשאלו?" + H.ans("תשובה: %s תלמידים" % H.BL_S),
             "25", "%s." % H.m("2 + 5 + 8 + 6 + 3 + 1 = 25"), [(1, "25."), (0, "כל אפשרות אחרת.")],
             errors="6 — ספירת העמודות (ערכים) במקום התלמידים; 15 — סכום הערכים 0..5.")
    b = Part("ב", 1, "knowledge", "מהו השכיח של מספר הספרים?" + H.ans("תשובה: %s" % H.BL_S),
             "2", "הערך בעל השכיחות הגבוהה ביותר: 2 ספרים (8 תלמידים).", [(1, "2."), (0, "כל אפשרות אחרת, כולל 8 (השכיחות עצמה).")],
             errors="8 — בלבול בין הערך לשכיחותו.")
    c = Part("ג", 2, "process", "מהו החציון של מספר הספרים? הסבירו כיצד מצאתם אותו." + H.work(58) + H.ans("תשובה: %s" % H.BL_S),
             "2", "25 ערכים ממוינים — החציון הוא הערך ה־13. השכיחויות המצטברות: 2, 7, 15 — הערך ה־13 נמצא בקבוצת ה־2. החציון 2.",
             [(2, "2 עם הסבר (מיקום 13 מתוך 25 / שכיחויות מצטברות / רשימה ממוינת)."), (1, "2 ללא הסבר, או הסבר נכון עם ספירה שגויה."),
              (0, "כל אפשרות אחרת, כולל 2.5 (אמצע הערכים 0..5).")],
             errors="2.5 — חציון של השורה העליונה; 3 — אמצע טווח 1..5; 8 — שכיחות.", reasoning_credit=True)
    d = Part("ד", 2, "algorithmic", "מהו הממוצע של מספר הספרים לתלמיד? הציגו את דרך הפתרון." + H.work(58) + H.ans("תשובה: %s ספרים" % H.BL_S),
             "2.24", "סך הספרים: %s. הממוצע: %s." % (H.m("0·2 + 1·5 + 2·8 + 3·6 + 4·3 + 5·1 = 56"), H.m("56 : 25 = 2.24")),
             [(2, "2.24 עם חישוב ממוצע משוקלל."), (1, "חישוב נכון של 56 עם חלוקה שגויה (למשל ב־6), או טעות כפל אחת."),
              (0, "כל אפשרות אחרת, כולל 2.5 (ממוצע הערכים 0..5) ו־4.17 (25 : 6).")],
             errors="2.5 — ממוצע ללא שקלול; 4.17 — חלוקת מספר התלמידים במספר הערכים.")
    e = Part("ה", 2, "open",
             "המורה אמרה: &quot;הממוצע גדול מ־2, ולכן רוב התלמידים קראו יותר מ־2 ספרים.&quot;<br>האם המורה צודקת?" + H.yesno() +
             "<p>נמקו את תשובתכם בעזרת הנתונים.</p>" + H.work(76),
             "לא", "קראו יותר מ־2 ספרים: %s תלמידים מתוך 25 — פחות מחצי. הממוצע מושפע מהערכים הגבוהים (4 ו־5), אך רוב התלמידים (15) קראו 2 ספרים או פחות." % H.m("6 + 3 + 1 = 10"),
             [(2, "&quot;לא&quot; עם ספירה (10 מתוך 25, או 15 שקראו 2 או פחות) ומסקנה."),
              (1, "&quot;לא&quot; עם נימוק כללי נכון ללא ספירה (למשל &quot;ממוצע לא אומר רוב&quot;)."),
              (0, "כל אפשרות אחרת, כולל &quot;כן&quot; עם נימוק.")],
             errors="&quot;כן&quot; מאבחן זיהוי הממוצע עם ה&quot;רוב&quot; (בלבול ממוצע–שכיח/חציון).", reasoning_credit=True)
    return Question(
        n=16, domain="data", topic="סטטיסטיקה — מדדי מרכז מטבלת שכיחויות", skill="שכיח, חציון, ממוצע משוקלל; פירוש ממוצע",
        claim="התלמיד מחשב מדדי מרכז מטבלת שכיחויות ומבין מה הממוצע אומר ומה לא.",
        evidence="25, 2, 2 עם הסבר, 2.24 עם חישוב, &quot;לא&quot; עם 10 מתוך 25.",
        task="קריאת טבלה; חישובים; ביקורת טענה סטטיסטית.",
        difficulty="mid", representations=["טבלה → מספרי", "מספרי → טיעון"], literacy=False, minutes=7,
        stem="<p>בכיתה ט׳ נשאלו התלמידים כמה ספרים קראו בחופשת הקיץ. התוצאות מרוכזות בטבלה שלפניכם.</p>" + tbl,
        parts=[a, b, c, d, e],
        reference="הקרוב ביותר: שאלה 3 במבחן הרשמי (דירוגי מסעדה: סך הלקוחות, האם הממוצע יכול להיות 3) ושאלה 6 במבחן התרגול הקודם (דיאגרמת נקודות שערים). הבדלים: (1) טבלת שכיחויות עם 6 ערכים, לא דיאגרמה; (2) נדרשים שלושה מדדים שונים, והחציון מחייב ספירה מצטברת; (3) הטענה לביקורת היא &quot;ממוצע → רוב&quot; ולא &quot;ממוצע = המקסימום&quot;; (4) אין היגדי נכון/לא נכון.",
        accessibility="טבלה אחת קטנה; חמישה סעיפים קצרים; מחשבון זמין לחישוב 56 : 25.",
        notes="סעיף ה הוא פריט אוריינות נתונים: ההבחנה בין ממוצע לרוב. השכיח והחציון שווים (2), והממוצע שונה — הזדמנות לדיון.",
        check=check, critique=True,
    )
